export const PRODUCTS = CATEGORIES.flatMap((category) =>
  RAW[category].map(([type, color, price, description, meta], i) => {
    const id = `${category}-${String(i + 1).padStart(2, "0")}`;
    return { id, category, type, color, name: id, price, image: imageFor(id), description, meta };
  })
);

export function getProduct(id) {
  return PRODUCTS.find((p) => p.id === id);
}

// 관련 상품: 같은 카테고리 상품. 같은 종류(예: 니트끼리)를 맨 앞에 보여준다.
export function getRelated(id) {
  const product = getProduct(id);
  if (!product) return [];
  return PRODUCTS.filter((p) => p.id !== id && p.category === product.category).sort(
    (a, b) => (b.type === product.type) - (a.type === product.type)
  );
}
