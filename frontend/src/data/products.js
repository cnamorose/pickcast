// 실제 데이터셋 상품 ID와 매칭시키지 않아도 됨).
// 상품명은 팀 규칙대로 실제 이름 없이 번호로 구분한다.
//
// 이미지 교체 방법: frontend/public/images/ 에 "TOP-01.jpg" 처럼 id 이름으로 파일을 넣고
// 아래 USE_LOCAL_IMAGES를 true로 바꾸면 된다. 그 전까지는 임시 이미지(picsum)를 쓴다.
const USE_LOCAL_IMAGES = false;

function imageFor(id) {
  return USE_LOCAL_IMAGES
    ? `/images/${id}.jpg`
    : `https://picsum.photos/seed/${id.toLowerCase()}/600/600`;
}

