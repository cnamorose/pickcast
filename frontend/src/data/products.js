export const PRODUCTS = CATEGORIES.flatMap((category) =>
  RAW[category].map(([price, description, meta], i) => {
    const id = `${category}-${String(i + 1).padStart(2, "0")}`;
    return { id, category, name: id, price, image: imageFor(id), description, meta };
  })
);

export function getProduct(id) {
  return PRODUCTS.find((p) => p.id === id);
}

// 관련 상품: 상품이 많아져서 전체 대신 같은 카테고리 상품만 보여준다.
export function getRelated(id) {
  const product = getProduct(id);
  if (!product) return [];
  return PRODUCTS.filter((p) => p.id !== id && p.category === product.category);
}
